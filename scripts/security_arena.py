"""Independent ordinary SQL permission regressions for the public hardened profile.

Only a fresh synthetic database on 127.0.0.1 is used. The already isolated
PostgreSQL 17 service must expose the disposable arena_admin administrator.
Existing PG/WMS credentials and password files are never consumed. The service
HBA is never edited: a wrong-password probe reports whether its authentication
actually requires the generated password or accepts passwordless connections.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import secrets
import subprocess
import sys

from migrate_core import build_script


class ArenaError(RuntimeError):
    pass


def now():
    return datetime.now(timezone.utc).isoformat()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--psql', required=True)
    parser.add_argument('--port', required=True, type=int)
    parser.add_argument('--go', required=True)
    parser.add_argument('--report', required=True)
    args = parser.parse_args()
    if not 1 <= args.port <= 65535:
        parser.error('port must be in 1..65535')
    root = Path(__file__).resolve().parent.parent
    suffix = secrets.token_hex(8)
    database = 'wms_kernel_test_arena_' + suffix
    owner, api, worker, module = ['arena_' + kind + '_' + suffix for kind in ('owner', 'api', 'worker', 'module')]
    run = root / 'work' / ('security-arena-' + suffix)
    run.mkdir(parents=True)
    target = Path(args.report)
    if not target.is_absolute():
        target = root / target
    target.parent.mkdir(parents=True, exist_ok=True)
    clean_env = {key: value for key, value in os.environ.items() if not key.startswith(('PG', 'WMS_'))}
    # An explicit missing passfile suppresses libpq's per-user default passfile.
    clean_env.update(PGPASSFILE=str(run / 'no-user-password-file'), PGSERVICEFILE=str(run / 'no-user-service-file'), PGSYSCONFDIR=str(run), PGCONNECT_TIMEOUT='5', PGSSLMODE='disable')
    passwords = [secrets.token_hex(32), secrets.token_hex(32)]
    base = [args.psql, '-X', '-q', '-At', '-w', '-h', '127.0.0.1', '-p', str(args.port), '-U', 'arena_admin', '-v', 'ON_ERROR_STOP=1']
    created_roles = []
    database_created = False
    sentinel_created = False
    report = {'started_at': now(), 'scope': 'fresh synthetic dedicated client database; ordinary SELECT/EXECUTE permission regression', 'profile': 'onprem-v1', 'host': '127.0.0.1', 'port': args.port, 'database': database, 'roles': {'owner': owner, 'api': api, 'worker': worker, 'module': module}, 'run_directory': str(run), 'matrix': [], 'test_results': [], 'cleanup': {}, 'all_pass': False, 'authentication': {'service_hba_modified': False, 'inherited_pg_credentials_used': False, 'signing_key': 'generated by database and inserted under owner; never returned to runner or red tests', 'request_context_supplied_to_tests': False}}
    sources = [root / 'scripts/security_arena.py', root / 'scripts/migrate_core.py', root / 'internal/postgres/store_redteam_credentials_integration_test.go', root / 'db/profiles/hardened-v1.sql', root / 'db/profiles/onprem-v1.sql', root / 'db/bootstrap/onprem-grants.psql', root / 'db/bootstrap/grants.psql', root / 'db/bootstrap/backend-grants.psql'] + sorted((root / 'db/migrations').glob('*.sql'))

    def source_hashes():
        return {str(path.relative_to(root)).replace('\\', '/'): hashlib.sha256(path.read_bytes()).hexdigest() for path in sources}

    def scrub(text):
        for password in passwords:
            text = text.replace(password, '[synthetic password redacted]')
        return text

    def execute(command, label, *, env=None, sql=None, checked=True, timeout=120):
        try:
            result = subprocess.run(command, input=sql, cwd=root, env=env or clean_env, capture_output=True, text=True, encoding='utf8', errors='replace', timeout=timeout)
        except (OSError, subprocess.TimeoutExpired) as error:
            raise ArenaError(label + ': execution infrastructure error') from error
        output = scrub(result.stdout + result.stderr)
        path = run / (label + '.log')
        path.write_text(output, encoding='utf8')
        if checked and result.returncode:
            raise ArenaError(label + ': command failed; inspect ' + str(path))
        return result, path

    def sql(query, label, db='postgres', variables=None):
        command = base + ['-d', db]
        for key, value in (variables or {}).items():
            command += ['-v', key + '=' + value]
        return execute(command, label, sql=query)[0].stdout.strip()

    try:
        report['source_hashes'] = source_hashes()
        report['postgres_version'] = sql('SHOW server_version;', 'postgres-version')
        if not report['postgres_version'].startswith('17.'):
            raise ArenaError('PostgreSQL 17 is required for this independent matrix')
        report['go_version'] = execute([args.go, 'version'], 'go-version')[0].stdout.strip()
        sql("CREATE ROLE " + owner + " NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;", 'create-owner')
        created_roles.append(owner)
        sql("SET password_encryption='scram-sha-256'; CREATE ROLE " + api + " LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '" + passwords[0] + "';", 'create-api')
        created_roles.append(api)
        sql("SET password_encryption='scram-sha-256'; CREATE ROLE " + worker + " LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '" + passwords[1] + "';", 'create-worker')
        created_roles.append(worker)
        sql('CREATE ROLE ' + module + ' NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;', 'create-module')
        created_roles.append(module)
        # The frozen baseline characterization names this legacy owner. It may
        # already exist in CI; never alter or delete an existing role.
        existed = sql("SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='wms_test_owner');", 'owner-sentinel-probe')
        if existed != 't':
            sql('CREATE ROLE wms_test_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;', 'create-owner-sentinel')
            sentinel_created = True
        sql('CREATE DATABASE ' + database + ' OWNER ' + owner + ';', 'create-database')
        database_created = True
        sql('REVOKE ALL ON DATABASE ' + database + ' FROM PUBLIC; GRANT CONNECT ON DATABASE ' + database + ' TO ' + api + ',' + worker + ';', 'database-access')
        sql('SET ROLE ' + owner + ';\n' + build_script(root), 'core-migrations', db=database)
        variables = {'runtime_role': api, 'module_role': module}
        for path in ('db/bootstrap/grants.psql', 'db/bootstrap/backend-grants.psql'):
            sql('SET ROLE ' + owner + ';\n' + (root / path).read_text(encoding='utf8'), 'legacy-' + Path(path).stem, db=database, variables=variables)
        sql('SET ROLE ' + owner + ';\n' + (root / 'db/profiles/hardened-v1.sql').read_text(encoding='utf8'), 'hardened-profile', db=database)
        sql('SET ROLE ' + owner + ';\n' + (root / 'db/profiles/onprem-v1.sql').read_text(encoding='utf8'), 'onprem-profile', db=database)
        report['api_binding'] = {'boundary': 'this dedicated client database; organizations and warehouses are internal employee-permission scopes'}
        variables = {'api_role': api, 'worker_role': worker}
        sql('SET ROLE ' + owner + ';\n' + (root / 'db/bootstrap/onprem-grants.psql').read_text(encoding='utf8'), 'onprem-grants', db=database, variables=variables)
        sql("SET ROLE " + owner + "; INSERT INTO hardened_private.signing_keys(login,key) SELECT '" + api + "',hardened_crypto.gen_random_bytes(32);", 'owner-signing-key-insertion', db=database)
        verifier = sql("SELECT (rolpassword LIKE 'SCRAM-SHA-256$%') FROM pg_authid WHERE rolname='" + api + "';", 'password-verifier')
        report['authentication']['scram_verifier_present'] = verifier == 't'
        if verifier != 't':
            raise ArenaError('synthetic runtime SCRAM verifier is missing')
        member = sql("SELECT pg_has_role('" + api + "','" + owner + "','MEMBER');", 'actual-owner-membership')
        report['actual_owner_membership'] = member == 't'
        if member != 'f':
            raise ArenaError('synthetic API role unexpectedly belongs to actual owner')
        runtime_base = [args.psql, '-X', '-q', '-w', '-h', '127.0.0.1', '-p', str(args.port), '-U', api, '-d', database, '-v', 'ON_ERROR_STOP=1', '-c', 'SELECT 1;']
        execute(runtime_base, 'correct-runtime-password', env=dict(clean_env, PGPASSWORD=passwords[0]))
        wrong, _ = execute(runtime_base, 'wrong-runtime-password', env=dict(clean_env, PGPASSWORD=secrets.token_hex(32)), checked=False)
        report['authentication']['wrong_password_rejected'] = wrong.returncode != 0
        report['authentication']['observed_mode'] = 'password_required_with_scram_verifier' if wrong.returncode else 'service_accepts_passwordless_connection; this run verifies authorization, not SCRAM handshake'
        env = dict(clean_env, WMS_ARENA_LOCAL_ONLY='1', WMS_TEST_ADMIN_DSN=f'postgres://arena_admin@127.0.0.1:{args.port}/{database}?sslmode=disable', WMS_TEST_RUNTIME_DSN=f'postgres://{api}:{passwords[0]}@127.0.0.1:{args.port}/{database}?sslmode=disable')
        commands = [
            ('vet', [args.go, 'vet', '-tags=integration,arena', './internal/postgres']),
            ('tests', [args.go, 'test', '-race', '-tags=integration,arena', './internal/postgres', '-run', '^TestRedTeamCredentials', '-count=1', '-timeout=180s', '-json']),
        ]
        for label, command in commands:
            result, path = execute(command, label, env=env, checked=False, timeout=240)
            report[label] = {'command': command, 'exit_code': result.returncode, 'output': str(path), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
            if label == 'tests':
                for line in result.stdout.splitlines():
                    try:
                        event = json.loads(line)
                    except ValueError:
                        continue
                    output = event.get('Output', '')
                    if 'ARENA_MATRIX ' in output:
                        report['matrix'].append(json.loads(output.split('ARENA_MATRIX ', 1)[1]))
                    if event.get('Action') in ('pass', 'fail', 'skip') and event.get('Test'):
                        report['test_results'].append({'test': event['Test'], 'result': event['Action']})
        new_requirements = [case for case in report['test_results'] if case['test'].startswith('TestRedTeamCredentialsDeniedWithoutAPIContext/')]
        existing = [case for case in report['test_results'] if case['test'].startswith('TestRedTeamCredentialsExistingPrivilegeCharacterization/')]
        extra = [case for case in report['test_results'] if case['test'].startswith('TestRedTeamCredentialsHardenedRPCDenials/')]
        metadata = [case for case in report['test_results'] if case['test'].startswith('TestRedTeamCredentialsHardenedSafeMetadataCharacterization/')]
        report['new_requirement_results'] = new_requirements
        report['existing_characterization_results'] = existing
        report['additional_hardened_results'] = extra
        report['safe_metadata_characterization_results'] = metadata
        report['summary'] = {'frozen_denial_cases': len(new_requirements), 'frozen_denial_passes': sum(case['result'] == 'pass' for case in new_requirements), 'existing_characterization_cases': len(existing), 'existing_characterization_passes': sum(case['result'] == 'pass' for case in existing), 'additional_hardened_denials': len(extra), 'additional_hardened_denial_passes': sum(case['result'] == 'pass' for case in extra), 'safe_metadata_characterizations': len(metadata), 'safe_metadata_characterization_passes': sum(case['result'] == 'pass' for case in metadata), 'matrix_cases': len(report['matrix']), 'allowed_without_context': sum(row['actual'] == 'allowed' for row in report['matrix']), 'durable_side_effect_cases': sum(row['durable_side_effects'] for row in report['matrix']), 'unexpected_sqlstates': sum(row['sqlstate'] not in ('42501', '28000') for row in report['matrix']), 'skipped': sum(case['result'] == 'skip' for case in report['test_results'])}
        report['sources_unchanged_during_run'] = report['source_hashes'] == source_hashes()
        report['all_pass'] = report['vet']['exit_code'] == 0 and report['tests']['exit_code'] == 0 and len(new_requirements) == 22 and len(existing) == 8 and len(extra) == 13 and len(metadata) == 3 and len(report['matrix']) == 39 and report['sources_unchanged_during_run'] and all(case['result'] == 'pass' for case in report['test_results']) and all(row['actual'] == 'denied' and row['sqlstate'] in ('42501', '28000') and not row['durable_side_effects'] for row in report['matrix'])
        report['classification'] = 'Passing public-candidate checks are characterization of the prepared implementation. Baseline 22 failing reduced-trust requirements are retained separately in red report; no new product implementation was changed for this run.'
    except (ArenaError, OSError, ValueError) as error:
        report['error'] = scrub(str(error))
    finally:
        if database_created:
            try:
                sql('DROP DATABASE ' + database + ' WITH (FORCE);', 'cleanup-database')
                report['cleanup']['database_dropped'] = True
            except ArenaError as error:
                report['cleanup']['database_error'] = str(error)
                report['all_pass'] = False
        for role in reversed(created_roles):
            try:
                sql('DROP ROLE ' + role + ';', 'cleanup-' + role)
                report['cleanup'].setdefault('roles_dropped', []).append(role)
            except ArenaError as error:
                report['cleanup'].setdefault('role_errors', []).append(str(error))
                report['all_pass'] = False
        if sentinel_created:
            try:
                sql('DROP ROLE wms_test_owner;', 'cleanup-owner-sentinel')
                report['cleanup']['created_sentinel_dropped'] = True
            except ArenaError as error:
                report['cleanup']['sentinel_error'] = str(error)
                report['all_pass'] = False
        report['finished_at'] = now()
        target.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
    print(json.dumps({'report': str(target), 'all_pass': report['all_pass'], 'summary': report.get('summary'), 'error': report.get('error')}, indent=2))
    return 0 if report['all_pass'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
